/**
 * Check cross-document consistency for a user
 * Compares extracted names and dates of birth across all verification documents
 */
async function checkCrossDocumentConsistency(userId) {
	try {
		// Get all documents with verification data for this user
		const result = await pool.query(
			`
			SELECT
				vd.id as document_id,
				vd.document_type,
				vd.status,
				vd.extracted_data,
				dv.authenticity_score,
				dv.fraud_risk
			FROM verification_documents vd
			LEFT JOIN document_verifications dv ON vd.id = dv.document_id
			WHERE vd.user_id = $1
			ORDER BY vd.created_at DESC
			`,
			[userId],
		);

		const documents = result.rows;
		if (documents.length === 0) {
			return { documents: [], inconsistencies: [], consistent: true };
		}

		// Extract normalized names and DOBs from each document
		const docProfiles = documents.map((doc) => {
			const data =
				typeof doc.extracted_data === 'string'
					? JSON.parse(doc.extracted_data || '{}')
					: doc.extracted_data || {};

			const names = extractNames(data);
			const dobs = extractDOBs(data);

			return {
				document_id: doc.document_id,
				document_type: doc.document_type,
				status: doc.status,
				names,
				dobs,
				authenticity_score: doc.authenticity_score,
				fraud_risk: doc.fraud_risk,
			};
		});

		// Find inconsistencies across documents
		const inconsistencies = [];
		const perDocReport = [];

		// Collect all unique names and DOBs across documents
		const allNames = new Set();
		const allDobs = new Set();
		docProfiles.forEach((dp) => {
			dp.names.forEach((n) => { allNames.add(n); });
			dp.dobs.forEach((d) => { allDobs.add(d); });
		});

		// If we have more than one document, check for name mismatches
		if (docProfiles.length > 1 && allNames.size > 1) {
			const _nameGroups = Array.from(allNames);
			// Find the most common name
			const nameCounts = {};
			docProfiles.forEach((dp) => {
				dp.names.forEach((n) => {
					nameCounts[n] = (nameCounts[n] || 0) + 1;
				});
			});
			const primaryName = Object.entries(nameCounts).sort((a, b) => b[1] - a[1])[0]?.[0];

			docProfiles.forEach((dp) => {
				const hasPrimary = dp.names.some((n) => n === primaryName);
				if (!hasPrimary && dp.names.length > 0) {
					inconsistencies.push({
						type: 'name_mismatch_across_documents',
						severity: 'high',
						details: `Document ${dp.document_id} (${dp.document_type}) contains name(s) "${dp.names.join(', ')}" that do not match primary name "${primaryName}"`,
						document_id: dp.document_id,
					});
				}
			});
		}

		// Check for DOB mismatches
		if (docProfiles.length > 1 && allDobs.size > 1) {
			const dobCounts = {};
			docProfiles.forEach((dp) => {
				dp.dobs.forEach((d) => {
					dobCounts[d] = (dobCounts[d] || 0) + 1;
				});
			});
			const primaryDob = Object.entries(dobCounts).sort((a, b) => b[1] - a[1])[0]?.[0];

			docProfiles.forEach((dp) => {
				const hasPrimary = dp.dobs.some((d) => d === primaryDob);
				if (!hasPrimary && dp.dobs.length > 0) {
					inconsistencies.push({
						type: 'dob_mismatch_across_documents',
						severity: 'high',
						details: `Document ${dp.document_id} (${dp.document_type}) contains DOB(s) "${dp.dobs.join(', ')}" that do not match primary DOB "${primaryDob}"`,
						document_id: dp.document_id,
					});
				}
			});
		}

		// Build per-document consistency report
		docProfiles.forEach((dp) => {
			const docInconsistencies = inconsistencies.filter((i) => i.document_id === dp.document_id);
			perDocReport.push({
				document_id: dp.document_id,
				document_type: dp.document_type,
				status: dp.status,
				extracted_names: dp.names,
				extracted_dobs: dp.dobs,
				inconsistencies: docInconsistencies,
				is_consistent: docInconsistencies.length === 0,
			});
		});

		return {
			documents: perDocReport,
			inconsistencies,
			consistent: inconsistencies.length === 0,
		};
	} catch (error) {
		console.error('Cross-document consistency check error:', error);
		return { documents: [], inconsistencies: [], consistent: true, error: error.message };
	}
}

/**
 * Extract normalized names from OCR extracted data
 */
function extractNames(data) {
	const names = [];
	// Try common field names
	const nameFields = [
		'name',
		'student_name',
		'employee_name',
		'full_name',
		'candidate_name',
		'holder_name',
	];
	for (const field of nameFields) {
		if (data[field] && typeof data[field] === 'string') {
			names.push(normalizeName(data[field]));
		}
	}
	// Also check metadata.names if present
	if (data.names && Array.isArray(data.names)) {
		data.names.forEach((n) => { names.push(normalizeName(n)); });
	}
	return [...new Set(names)].filter(Boolean);
}

/**
 * Extract normalized dates of birth from OCR extracted data
 */
function extractDOBs(data) {
	const dobs = [];
	const dobFields = ['date_of_birth', 'dob', 'birth_date', 'birthdate', 'date_of_birth'];
	for (const field of dobFields) {
		if (data[field] && typeof data[field] === 'string') {
			dobs.push(normalizeDate(data[field]));
		}
	}
	return [...new Set(dobs)].filter(Boolean);
}

/**
 * Normalize a name string for comparison
 */
function normalizeName(name) {
	return name
		.toLowerCase()
		.replace(/[^a-z\s]/g, '')
		.replace(/\s+/g, ' ')
		.trim();
}

/**
 * Normalize a date string for comparison
 */
function normalizeDate(dateStr) {
	if (!dateStr) return null;
	// Remove common separators and normalize
	const normalized = dateStr.replace(/[/.-]/g, '-').replace(/\s+/g, ' ').trim().toLowerCase();
	return normalized;
}

