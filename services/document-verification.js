/**
 * Detect metadata anomalies in document file buffer
 * Analyzes PDF metadata and image headers for signs of tampering
 */
async function detectMetadataAnomalies(fileBuffer, documentType) {
	const flags = [];

	try {
		const mimeType = detectMimeType(fileBuffer);

		if (mimeType === 'application/pdf') {
			const pdfParse = require('pdf-parse');
			const pdfData = await pdfParse(fileBuffer);
			const info = pdfData.info || {};

			// Check for editing software fingerprints
			const producer = (info.Producer || '').toLowerCase();
			const creator = (info.Creator || '').toLowerCase();
			const softwareSignatures = [
				'photoshop',
				'gimp',
				'inkscape',
				'illustrator',
				'canva',
				'figma',
				'sejda',
				'smallpdf',
				'ilovepdf',
			];
			for (const sig of softwareSignatures) {
				if (producer.includes(sig) || creator.includes(sig)) {
					flags.push({
						type: 'editing_software_detected',
						severity: 'medium',
						details: `PDF generated by editing software: ${sig} (Producer: ${info.Producer || 'unknown'}, Creator: ${info.Creator || 'unknown'})`,
					});
				}
			}

			// Check for suspicious PDF generators (non-standard)
			const standardGenerators = [
				'microsoft',
				'acrobat',
				'pdflatex',
				'luatex',
				'xetex',
				'libreoffice',
				'word',
				'excel',
			];
			const isStandard = standardGenerators.some(
				(g) => producer.includes(g) || creator.includes(g),
			);
			if (!isStandard && (producer || creator)) {
				flags.push({
					type: 'unusual_pdf_generator',
					severity: 'low',
					details: `Unusual PDF generator detected: Producer="${info.Producer || ''}", Creator="${info.Creator || ''}"`,
				});
			}

			// Check creation vs modification date inconsistency
			if (info.CreationDate && info.ModDate) {
				const created = parsePdfDate(info.CreationDate);
				const modified = parsePdfDate(info.ModDate);
				if (created && modified && modified < created) {
					flags.push({
						type: 'date_inconsistency',
						severity: 'high',
						details: `PDF modification date (${info.ModDate}) is before creation date (${info.CreationDate})`,
					});
				}
			}

			// Check for missing metadata (suspicious for official docs)
			if (documentType === 'education_certificate' || documentType === 'employment_letter') {
				if (!info.CreationDate && !info.Creator && !info.Producer) {
					flags.push({
						type: 'missing_metadata',
						severity: 'low',
						details:
							'Official document has no PDF metadata — possible scanned forgery or stripped metadata',
					});
				}
			}
		} else if (mimeType?.startsWith('image/')) {
			// Basic image buffer inspection for EXIF-like signatures
			const bufStr = fileBuffer.toString('binary', 0, Math.min(fileBuffer.length, 4096));

			// Look for common editing software signatures in image metadata
			const imgSoftware = [
				{ sig: 'Adobe Photoshop', name: 'Photoshop' },
				{ sig: 'GIMP', name: 'GIMP' },
				{ sig: 'Paint.NET', name: 'Paint.NET' },
				{ sig: 'Canva', name: 'Canva' },
			];
			for (const sw of imgSoftware) {
				if (bufStr.includes(sw.sig)) {
					flags.push({
						type: 'editing_software_detected',
						severity: 'medium',
						details: `Image metadata indicates editing with ${sw.name}`,
					});
				}
			}

			// Check for EXIF header presence and basic structure
			if (fileBuffer.length > 4) {
				// JPEG starts with FF D8 FF; look for EXIF marker FF E1
				if (fileBuffer[0] === 0xff && fileBuffer[1] === 0xd8) {
					let hasExif = false;
					for (let i = 0; i < Math.min(fileBuffer.length - 1, 65536); i++) {
						if (fileBuffer[i] === 0xff && fileBuffer[i + 1] === 0xe1) {
							hasExif = true;
							break;
						}
					}
					if (!hasExif && (documentType === 'id_document' || documentType === 'certification')) {
						flags.push({
							type: 'missing_exif',
							severity: 'low',
							details: 'JPEG image lacks EXIF metadata — may be a screenshot or resaved image',
						});
					}
				}
			}
		}
	} catch (error) {
		console.error('Metadata anomaly detection error:', error);
		flags.push({
			type: 'metadata_analysis_failed',
			severity: 'low',
			details: `Could not analyze metadata: ${error.message}`,
		});
	}

	return flags;
}

/**
 * Detect MIME type from file buffer magic numbers
 */
function detectMimeType(buffer) {
	if (buffer.length < 4) return null;
	// PDF
	if (buffer.toString('ascii', 0, 4) === '%PDF') return 'application/pdf';
	// JPEG
	if (buffer[0] === 0xff && buffer[1] === 0xd8) return 'image/jpeg';
	// PNG
	if (buffer[0] === 0x89 && buffer[1] === 0x50 && buffer[2] === 0x4e && buffer[3] === 0x47)
		return 'image/png';
	// WEBP
	if (buffer.length >= 12 && buffer.toString('ascii', 8, 12) === 'WEBP') return 'image/webp';
	return null;
}

/**
 * Parse PDF date string (D:YYYYMMDDHHmmSSOHH'mm')
 */
function parsePdfDate(dateStr) {
	if (!dateStr) return null;
	const match = dateStr.match(/D:(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})/);
	if (match) {
		return new Date(`${match[1]}-${match[2]}-${match[3]}T${match[4]}:${match[5]}:${match[6]}`);
	}
	return null;
}

